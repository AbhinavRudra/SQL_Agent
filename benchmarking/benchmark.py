@dataclass
class BenchmarkRecord:
    query: str
    baseline_sql: str
    baseline_error: Optional[str]
    baseline_ex_match: bool
    cav_sql: str
    cav_error: Optional[str]
    cav_ex_match: bool
    cav_interventions: int

# ============================================================
# Main Runner
# ============================================================

def run_benchmark():
    ollama_model = os.environ.get("OLLAMA_MODEL", "hf.co/defog/sqlcoder-7b-2:Q5_K_M")
    
    print("Initializing CAV-SQL System...")
    cav_system = CAVWorkflow(
        engine=engine,
        schema_path=SCHEMA_PATH,
        ollama_model=ollama_model,
    )

    records: list[BenchmarkRecord] = []
    
    baseline_correct = 0
    cav_correct = 0
    total_interventions = 0
    total_queries = len(BENCHMARK_QUERIES)

    for i, item in enumerate(BENCHMARK_QUERIES, 1):
        Q = item["Q"]
        gold_sql = item["gold_sql"]
        
        print(f"\n{'='*80}")
        print(f"Test {i}/{total_queries}: {Q}")
        print(f"{'='*80}")

        # 1. Get Ground Truth Data
        gold_res = execute_sql(gold_sql)

        # 2. Run Baseline (Control Group)
        bl = baseline_query(Q, cav_system.schema_summary, cav_system.llm)
        bl_match = compare_results(bl, gold_res)
        if bl_match:
            baseline_correct += 1

        # 3. Run CAV-SQL (Experimental Group)
        print("\n[CAV-SQL] Running workflow...")
        state = cav_system.run(Q)
        
        # Parse the JSON execution result returned by the LangGraph executor
        cav_res_json = {}
        cav_exec_error = None
        try:
            cav_res_json = json.loads(state.get("execution_result", "{}"))
            # Convert lists back to tuples for strict set comparison
            if "rows" in cav_res_json:
                cav_res_json["rows"] = [tuple(r) for r in cav_res_json["rows"]]
        except Exception:
            cav_exec_error = str(state.get("execution_result"))

        cav_match = compare_results(cav_res_json, gold_res)
        if cav_match:
            cav_correct += 1
        
        interventions = len(state.get("error_history", []))
        total_interventions += interventions

        # 4. Save Record
        records.append(BenchmarkRecord(
            query=Q,
            baseline_sql=bl["sql"],
            baseline_error=bl["error"],
            baseline_ex_match=bl_match,
            cav_sql=state.get("final_sql") or state.get("draft_sql", ""),
            cav_error=cav_exec_error,
            cav_ex_match=cav_match,
            cav_interventions=interventions
        ))

    # --- Write CSV ---
    with open(RESULTS_CSV, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(asdict(records[0]).keys()))
        writer.writeheader()
        writer.writerows([asdict(r) for r in records])

    # --- Output Formal Academic Summary ---
    print(f"\n\n{'='*40}")
    print("📊 CAV-SQL BENCHMARK RESULTS")
    print(f"{'='*40}")
    print(f"Total Queries Evaluated: {total_queries}")
    print(f"Baseline Execution Accuracy (EX): {(baseline_correct/total_queries)*100:.1f}%")
    print(f"CAV-SQL Execution Accuracy (EX):  {(cav_correct/total_queries)*100:.1f}%")
    print(f"Total CAV Interventions: {total_interventions}")
    print(f"\nDetailed telemetry saved to: {RESULTS_CSV}")

if __name__ == "__main__":
    run_benchmark()