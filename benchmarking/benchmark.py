# ============================================================
# Core Helpers
# ============================================================

def execute_sql(sql: str) -> dict:
    """Runs SQL securely and returns rows, columns, or an error."""
    try:
        with engine.connect() as conn:
            result = conn.execute(sa_text(sql))
            rows = result.fetchall()
            columns = list(result.keys())
        return {"rows": [tuple(r) for r in rows], "columns": columns, "error": None}
    except Exception as e:
        return {"rows": [], "columns": [], "error": str(e)}

def compare_results(ai_result: dict, gold_result: dict) -> bool:
    """
    Mathematical Execution Equivalence (EX).
    Compares two result sets using unordered sets. 
    Returns True if the LLM output perfectly matches the Ground Truth data.
    """
    if ai_result.get("error") or gold_result.get("error"):
        return False
    # Use sets to ignore row ordering
    return set(ai_result.get("rows", [])) == set(gold_result.get("rows", []))

# ============================================================
# Baseline Execution (No CAV)
# ============================================================

def baseline_query(question: str, schema_summary: str, llm: ChatOllama) -> dict:
    """Simulates a standard LLM agent without pre-execution verification."""
    with open(PROMPT_PATH, "r") as f:
        template = f.read()
    
    prompt = template.format(question=question, schema=schema_summary)
    response = llm.invoke([HumanMessage(content=prompt)])
    sql = _sanitize_sql(_message_text(response.content))
    
    print("[Baseline] Executing Draft SQL...")
    result = execute_sql(sql)
    return {"sql": sql, **result}

